package com.wails.app;

import android.Manifest;
import android.content.ActivityNotFoundException;
import android.content.Intent;
import android.content.pm.PackageManager;
import android.net.Uri;
import android.webkit.WebView;

import androidx.activity.result.ActivityResultLauncher;
import androidx.appcompat.app.AppCompatActivity;
import androidx.core.app.ActivityCompat;
import androidx.webkit.JavaScriptReplyProxy;
import androidx.webkit.WebMessageCompat;
import androidx.webkit.WebViewCompat;
import androidx.webkit.WebViewFeature;

import com.google.zxing.client.android.Intents;
import com.journeyapps.barcodescanner.ScanContract;
import com.journeyapps.barcodescanner.ScanIntentResult;
import com.journeyapps.barcodescanner.ScanOptions;

import org.json.JSONObject;

import java.util.Collections;
import java.util.regex.Pattern;

/** Opens the offline scanner on behalf of the top-level Meerkat settings page. */
final class PairingQrScanner {
    // Matches the canonical value generated by Hub's randomPairingCode.
    private static final Pattern PAIRING_CODE = Pattern.compile("MEERKAT-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}");
    private static final Pattern REQUEST_ID = Pattern.compile("[0-9a-f]{16}");

    private final AppCompatActivity activity;
    private final ActivityResultLauncher<ScanOptions> launcher;
    private ScanRequest pending;

    static void attach(AppCompatActivity activity, WebView webView, String shellOrigin) {
        if (!WebViewFeature.isFeatureSupported(WebViewFeature.WEB_MESSAGE_LISTENER)
                || !activity.getPackageManager().hasSystemFeature(PackageManager.FEATURE_CAMERA_ANY)) {
            return;
        }
        PairingQrScanner scanner = new PairingQrScanner(activity);
        Uri trustedOrigin = Uri.parse(shellOrigin);
        WebViewCompat.addWebMessageListener(webView, "meerkatPairingScanner", Collections.singleton(shellOrigin),
                (view, message, origin, isMainFrame, reply) -> {
                    // A DSH iframe must not be able to open the camera or receive a code.
                    if (isMainFrame && trustedOrigin.equals(origin)
                            && message.getType() == WebMessageCompat.TYPE_STRING) {
                        scanner.start(message.getData(), reply);
                    }
                });
    }

    private PairingQrScanner(AppCompatActivity activity) {
        this.activity = activity;
        launcher = activity.registerForActivityResult(new ScanContract(), this::onResult);
    }

    private void start(String id, JavaScriptReplyProxy reply) {
        if (id == null || !REQUEST_ID.matcher(id).matches()) return;
        ScanRequest request = new ScanRequest(id, reply);
        if (pending != null) {
            request.respond("busy", null);
            return;
        }
        ScanOptions options = new ScanOptions()
                .setCaptureActivity(PairingCaptureActivity.class)
                .setDesiredBarcodeFormats(ScanOptions.QR_CODE)
                .setPrompt("将 Hub 上的手机配对二维码对准取景框")
                .setBeepEnabled(false)
                .setOrientationLocked(false)
                .addExtra(Intents.Scan.SHOW_MISSING_CAMERA_PERMISSION_DIALOG, false);
        pending = request;
        try {
            launcher.launch(options);
        } catch (ActivityNotFoundException | SecurityException | IllegalStateException e) {
            pending = null;
            request.respond("unavailable", null);
        }
    }

    private void onResult(ScanIntentResult result) {
        ScanRequest request = pending;
        pending = null;
        // A recreated Activity has no request or page to receive the result.
        if (request == null || activity.isDestroyed()) return;
        String code = result.getContents();
        Intent intent = result.getOriginalIntent();
        if (intent != null && intent.getBooleanExtra(Intents.Scan.MISSING_CAMERA_PERMISSION, false)) {
            boolean canAskAgain = ActivityCompat.shouldShowRequestPermissionRationale(activity, Manifest.permission.CAMERA);
            request.respond(canAskAgain ? "permission" : "permission_settings", null);
        } else if (code == null) {
            request.respond("cancelled", null);
        } else if (code.startsWith("meerkat-pair://")) {
            Uri uri = Uri.parse(code);
            if (code.length() <= 1024 && "v1".equals(uri.getEncodedAuthority())
                    && "".equals(uri.getEncodedPath()) && uri.getFragment() == null
                    && uri.getQueryParameterNames().size() == 2
                    && uri.getQueryParameters("hub").size() == 1 && uri.getQueryParameters("code").size() == 1) {
                String address = uri.getQueryParameter("hub");
                String shortCode = uri.getQueryParameter("code");
                if (validAddress(address) && PAIRING_CODE.matcher(shortCode).matches()) {
                    request.respond("ok", shortCode, address);
                    return;
                }
            }
            request.respond("invalid", null);
        } else if (PAIRING_CODE.matcher(code).matches()) {
            request.respond("ok", code);
        } else {
            request.respond(code.startsWith("MEERKAT1:") ? "desktop_invite" : "invalid", null);
        }
    }

    private static boolean validAddress(String address) {
        try {
            java.net.URI target = new java.net.URI("http://" + address).parseServerAuthority();
            return address.equals(target.getRawAuthority()) && target.getHost() != null
                    && target.getRawUserInfo() == null && address.indexOf('%') < 0
                    && target.getPort() > 0 && target.getPort() <= 65535;
        } catch (java.net.URISyntaxException e) {
            return false;
        }
    }

    private static final class ScanRequest {
        final String id;
        final JavaScriptReplyProxy reply;

        ScanRequest(String id, JavaScriptReplyProxy reply) {
            this.id = id;
            this.reply = reply;
        }

        void respond(String status, String code) {
            respond(status, code, null);
        }

        void respond(String status, String code, String address) {
            String payload = "{\"id\":" + JSONObject.quote(id) + ",\"status\":" + JSONObject.quote(status)
                    + (address == null ? "" : ",\"hub\":" + JSONObject.quote(address))
                    + (code == null ? "" : ",\"code\":" + JSONObject.quote(code)) + "}";
            // The proxy targets the originating document. If it has navigated, the reply is dropped.
            reply.postMessage(payload);
        }
    }
}
